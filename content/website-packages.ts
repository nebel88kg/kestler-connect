/** Monatlicher Preis: Website über 12 Monate + Hosting, auf 10 € aufgerundet */
export function monthlyPrice(upfront: number): number {
  const raw = (upfront + HOSTING_MONTHLY * MIN_CONTRACT_MONTHS) / MIN_CONTRACT_MONTHS;
  return Math.ceil(raw / 10) * 10;
}

export function formatEuro(amount: number): string {
  return new Intl.NumberFormat("de-DE", {
    style: "currency",
    currency: "EUR",
    maximumFractionDigits: 0,
  }).format(amount);
}
